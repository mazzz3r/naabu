// Plugin detects IKEv2 (RFC 7296, ports 500/4500) by sending an IKE_SA_INIT
// with modern crypto proposals and confirming the version byte is 0x20 (vs
// 0x10 for IKEv1) and the initiator SPI is echoed.
type Plugin struct{}

// initBody is everything after the 8-byte initiator SPI of an IKE_SA_INIT.
var initBody = []byte{
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // Responder SPI
	0x22,                   // NextPayload: SA
	0x20,                   // Version: IKEv2
	0x22,                   // Exchange Type: IKE_SA_INIT
	0x08,                   // Flags: Initiator
	0x00, 0x00, 0x00, 0x00, // Message ID
	0x00, 0x00, 0x01, 0x50, // Message Length

	0x21, 0x00, 0x00, 0x84, // SA Payload
	0x00, 0x00, 0x00, 0x80, 0x01, 0x01, 0x00, 0x04, // Proposal 1
	0x03, 0x00, 0x00, 0x0C, 0x01, 0x00, 0x00, 0x0C, 0x80, 0x0E, 0x01, 0x00, // ENCR AES-CBC 256
	0x03, 0x00, 0x00, 0x08, 0x03, 0x00, 0x00, 0x0C, // INTEG SHA2-256
	0x03, 0x00, 0x00, 0x08, 0x02, 0x00, 0x00, 0x05, // PRF SHA2-256
	0x00, 0x00, 0x00, 0x08, 0x04, 0x00, 0x00, 0x0E, // DH Group 14

	0x00, 0x00, 0x00, 0x4C, 0x02, 0x01, 0x00, 0x03, // Proposal 2
	0x03, 0x00, 0x00, 0x0C, 0x01, 0x00, 0x00, 0x0C, 0x80, 0x0E, 0x00, 0x80, // ENCR AES-CBC 128
	0x03, 0x00, 0x00, 0x08, 0x03, 0x00, 0x00, 0x02, // INTEG SHA1
	0x00, 0x00, 0x00, 0x08, 0x04, 0x00, 0x00, 0x0E, // DH Group 14

	0x00, 0x00, 0x00, 0x88, 0x00, 0x0E, 0x00, 0x00, // KE Payload
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
}

func (Plugin) Name() string          { return "ikev2" }
func (Plugin) Ports() []uint16       { return []uint16{500, 4500} }
func (Plugin) Priority() int         { return 197 }
func (Plugin) Payload(uint16) []byte { return append(make([]byte, 8), initBody...) }

func (Plugin) Run(conn net.Conn, timeout time.Duration, target udp.Target) (*udp.Result, error) {
	initiator := make([]byte, 8)
	if _, err := rand.Read(initiator); err != nil {
		return nil, &udp.RandomizeError{Message: "initiator SPI"}
	}
	probe := append(append([]byte{}, initiator...), initBody...)

	response, err := udp.SendRecv(conn, probe, timeout)
	if err != nil {
		return nil, err
	}
	if len(response) < 28 || response[17] != 0x20 || !bytes.Equal(initiator, response[0:8]) {
		return nil, nil
	}
	return &udp.Result{
		Name:      "ikev2",
		ExtraInfo: "responder_spi=" + hex.EncodeToString(response[8:16]) + " message_id=" + hex.EncodeToString(response[20:24]),
	}, nil
}
