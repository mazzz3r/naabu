func (Plugin) Name() string          { return "ipsec" }
func (Plugin) Ports() []uint16       { return []uint16{500} }
func (Plugin) Priority() int         { return 198 }
func (Plugin) Payload(uint16) []byte { return append(make([]byte, 8), proposalBody...) }

func (Plugin) Run(conn net.Conn, timeout time.Duration, target udp.Target) (*udp.Result, error) {
	initiator := make([]byte, 8)
	if _, err := rand.Read(initiator); err != nil {
		return nil, &udp.RandomizeError{Message: "initiator SPI"}
	}
	probe := append(append([]byte{}, initiator...), proposalBody...)

	response, err := udp.SendRecv(conn, probe, timeout)
	if err != nil {
		return nil, err
	}
	if len(response) < 24 || !bytes.Equal(initiator, response[0:8]) {
		return nil, nil
	}
	return &udp.Result{
		Name:      "ipsec",
		ExtraInfo: "responder_spi=" + hex.EncodeToString(response[8:16]) + " message_id=" + hex.EncodeToString(response[20:24]),
	}, nil
}
